/* app_config.h - everything board / setup specific lives here.
 *
 * Board : WeAct STM32H723VGT6 (HSE 25 MHz, USB-C on PA11/PA12)
 * CAN   : 2x MCP2515 (16 MHz crystal) on SPI1 / SPI2, 1 Mbit/s
 * Motors: 4x RobStride EduLite 05, 2 per bus
 *
 *   motor index  bus   default CAN ID
 *        0       CAN1        1
 *        1       CAN1        2
 *        2       CAN2        1
 *        3       CAN2        2
 *
 * Two motors on the SAME bus must have DIFFERENT CAN IDs. New motors ship
 * with the same ID (usually 127): connect them one at a time and use the
 * calib "set CAN ID" command first (see CUBEMX_SETUP.md, "Bring-up").
 */
#ifndef APP_CONFIG_H
#define APP_CONFIG_H

#include "main.h"   /* HAL + pin labels generated by CubeMX */

/* ---------------------------------------------------------------- topology */
#define APP_NUM_BUS        2
#define APP_NUM_MOTORS     4
#define APP_MOTOR_BUS      {0, 0, 1, 1}
#define APP_MOTOR_IDS      {1, 2, 3, 4}   /* J1..J4 = CAN ID 1..4 (unique on both buses) */
#define APP_HOST_ID        0xFD

/* ---------------------------------------------------------------- timing */
#define APP_TICK_HZ        1000u   /* TIM6 interrupt rate                    */
#define APP_CTRL_HZ        500u    /* control loop rate (divides APP_TICK_HZ) */
#define APP_TELEM_DIV      5u      /* telemetry every N control ticks (100 Hz) */
#define APP_HEALTH_MS      200u    /* CAN health frame period                */

/* ---------------------------------------------------------------- gateway (gateway.h) */
#define APP_BOOT_GATEWAY   0       /* 1 = start in gateway mode (no host command needed) */
#define APP_GW_WD_MS       300u    /* watchdog used when APP_BOOT_GATEWAY = 1           */

/* ---------------------------------------------------------------- MCP2515 */
#define MCP2515_OSC_HZ     8000000u   /* crystal on YOUR modules: 8 MHz (1 Mbit/s is out of spec at
                                         * 8 MHz, see mcp2515.c). Swap to 16 MHz crystals if you see
                                         * error frames, then set 16000000u here. */
#define MCP2515_BITRATE    1000000u    /* RobStride default                   */

/* CubeMX handles (generated in main.c, or spi.c / tim.c when "pair of .c/.h
 * files per peripheral" is enabled - either way they are global). */
extern SPI_HandleTypeDef hspi1;
extern SPI_HandleTypeDef hspi2;
extern TIM_HandleTypeDef htim6;

#define CAN1_SPI_HANDLE    (&hspi1)
#define CAN2_SPI_HANDLE    (&hspi2)
#define APP_TICK_TIM       (&htim6)

/* GPIO labels: give these User Labels in CubeMX (right-click pin -> Enter User
 * Label) and CubeMX generates CAN1_CS_Pin / CAN1_CS_GPIO_Port etc. in main.h. */
#if !defined(CAN1_CS_Pin) || !defined(CAN1_INT_Pin) || !defined(CAN2_CS_Pin) || !defined(CAN2_INT_Pin)

/*  "In CubeMX label the pins CAN1_CS, CAN1_INT, CAN2_CS, CAN2_INT (see CUBEMX_SETUP.md)"
*/
#endif

/* USB device: the H723 USB runs on the OTG_HS peripheral (with its internal
 * Full-Speed PHY), so CubeMX names the CDC functions *_HS. */
#define APP_CDC_TRANSMIT(buf, len)   CDC_Transmit_HS((buf), (len))

#endif
